#!/bin/bash
# Assemble a local OTA for system-image-upgrader, following UBports'
# halium-generic-adaptation-build-tools prepare-fake-ota.sh (same ubuntu_command,
# same component order), but from pinned, verified A50 inputs and without the
# fake script's debug changes (sshd/adb unlock). Like the documented local OTA
# test, the .asc files are empty: this needs a recovery whose signature check is
# bypassed, and must never be shipped. A real channel signs every file.
#
# Usage: prepare-local-ota.sh OTA_ROOTFS_TAR GSI_TAR GSI_SHA256 DEVICE_TAR OUT_DIR
#   [FORMAT=1] adds `format system` (first install / migration); omit it for an
#   update of an already system-partition install.
set -euo pipefail
ROOTFS=$(realpath "${1:?usage: $0 OTA_ROOTFS_TAR GSI_TAR GSI_SHA256 DEVICE_TAR OUT_DIR}")
GSI=$(realpath "${2:?}"); GSI_SHA256=${3:?}
DEVICE=$(realpath "${4:?}")
OUT=$(realpath -m "${5:?}")
URL=https://system-image.ubports.com
CHANNEL=26.04-1.x/arm64/android9plus/daily
echo "$GSI_SHA256  $GSI" | sha256sum -c -
[ ! -e "$OUT/ubuntu_command" ] || { echo "E: $OUT already holds an OTA" >&2; exit 1; }
mkdir -p "$OUT"
for k in image-master image-signing; do
    [ -f "$OUT/$k.tar.xz" ] || curl -fsSL -o "$OUT/$k.tar.xz" "$URL/gpg/$k.tar.xz"
    [ -f "$OUT/$k.tar.xz.asc" ] || curl -fsSL -o "$OUT/$k.tar.xz.asc" "$URL/gpg/$k.tar.xz.asc"
done
cp "$ROOTFS" "$OUT/rootfs.tar.xz"
cp "$GSI" "$OUT/halium_halium_arm64.tar.xz"
cp "$DEVICE" "$OUT/device_a50.tar.xz"
V=$(mktemp -d); trap 'rm -rf "$V"' EXIT
mkdir -p "$V/system/etc/system-image/config.d"
cat > "$V/system/etc/system-image/channel.ini" <<EOF
[service]
base: system-image.ubports.com
http_port: 80
https_port: 443
channel: $CHANNEL
device: a50
EOF
ln -s ../client.ini "$V/system/etc/system-image/config.d/00_default.ini"
ln -s ../channel.ini "$V/system/etc/system-image/config.d/01_channel.ini"
tar --owner=root --group=root -cJf "$OUT/version.tar.xz" -C "$V" system
{
    echo '# Generated by a50 prepare-local-ota.sh (layout of UBports prepare-fake-ota.sh)'
    [ -z "${FORMAT:-}" ] || echo 'format system'
    echo 'load_keyring image-master.tar.xz image-master.tar.xz.asc'
    echo 'load_keyring image-signing.tar.xz image-signing.tar.xz.asc'
    echo 'mount system'
    for f in rootfs.tar.xz halium_halium_arm64.tar.xz device_a50.tar.xz version.tar.xz; do
        : > "$OUT/$f.asc"
        echo "update $f $f.asc"
    done
    echo 'unmount system'
} > "$OUT/ubuntu_command"
(cd "$OUT" && sha256sum *.tar.xz > SHA256SUMS)
cat "$OUT/ubuntu_command"
