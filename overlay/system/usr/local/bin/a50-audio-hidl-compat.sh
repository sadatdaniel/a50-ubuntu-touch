#!/bin/sh
# Make the 64-bit PulseAudio able to drive this device's 32-bit Samsung audio
# HAL, by way of Android's audio.hidl_compat wrapper.
#
# Two things are needed, and both are lost on every boot:
#
# 1. The wrapper has to be present at the HAL name PulseAudio resolves.
#    PulseAudio runs on the HOST, so the bind mount has to be in the host
#    mount namespace. The LXC mount hook in scripts/apply-device-workarounds.sh
#    does the same bind inside the CONTAINER's namespace, which is what the
#    container's own HAL service needs - it does nothing for PulseAudio, which
#    silently gets the 12 KB generic stub instead and discards every write.
#    (/android/... and /var/lib/lxc/android/rootfs/... are the same inode.)
#
# 2. The wrapper is loaded out of /vendor/lib64/hw/, so Android's linker
#    resolves it in the "sphal" namespace - whose search paths are vendor/odm
#    only, and whose allowlist into the "default" namespace does not include
#    libaudiohal.so. Without this the load fails with
#        dlopen failed: library "libaudiohal.so" not found
#    Adding the three framework audio-HAL client libraries to the
#    sphal->default link lets it resolve; they themselves live in
#    /android/system/lib64, which the default namespace does search.
#
# /linkerconfig/ld.config.txt is regenerated by linkerconfig on every boot, so
# the edit has to be re-applied each time, before PulseAudio starts.
#
# Verified working: /dev/hwbinder open in the PulseAudio process, and playback
# through sink.primary-out producing real abox_rdma_trigger / tfa_start
# activity in dmesg. See docs/experiments/007-abox-firmware-too-early.md.
set -u

LD_CONF=/linkerconfig/ld.config.txt
WRAPPER=/android/system/lib64/hw/audio.hidl_compat.default.so
HAL_NAME=/android/vendor/lib64/hw/audio.primary.default.so
ANCHOR='namespace.sphal.link.default.shared_libs += libfdtrack.so'
LIBS='libaudiohal.so libaudiohal@5.0.so libaudiohal_deathhandler.so'

log() { echo "a50-audio-hidl-compat: $*"; }

[ -e "$WRAPPER" ] || { log "wrapper missing: $WRAPPER"; exit 0; }

# linkerconfig writes this while the Android container comes up; wait for it.
i=0
while [ ! -s "$LD_CONF" ] && [ $i -lt 60 ]; do
    sleep 1
    i=$((i + 1))
done
if [ ! -s "$LD_CONF" ]; then
    log "$LD_CONF never appeared; audio HAL will fall back to the stub"
    exit 0
fi

if grep -q 'libaudiohal.so' "$LD_CONF"; then
    log "ld.config.txt already patched"
else
    if ! grep -qF "$ANCHOR" "$LD_CONF"; then
        log "anchor line absent from $LD_CONF - not patching blindly"
        exit 0
    fi
    tmp=$(mktemp)
    ins=""
    for l in $LIBS; do
        ins="${ins}namespace.sphal.link.default.shared_libs += ${l}\n"
    done
    awk -v anchor="$ANCHOR" -v ins="$ins" '
        $0 == anchor { print; printf "%s", ins; next }
        { print }
    ' "$LD_CONF" > "$tmp" && cat "$tmp" > "$LD_CONF"
    rm -f "$tmp"
    log "patched ld.config.txt (sphal -> default: $LIBS)"
fi

# Present the 64-bit Binder wrapper at the HAL name PulseAudio resolves.
if [ "$(stat -c %s "$HAL_NAME" 2>/dev/null)" = "$(stat -c %s "$WRAPPER" 2>/dev/null)" ]; then
    log "wrapper already in place at $HAL_NAME"
else
    if mount --bind "$WRAPPER" "$HAL_NAME"; then
        log "bind-mounted wrapper over $HAL_NAME"
    else
        log "bind mount failed"
    fi
fi
